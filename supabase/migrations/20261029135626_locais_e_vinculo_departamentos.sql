-- Locais do campus Sede (RF01) e vínculo dos departamentos com o local onde funcionam (UC37).
-- Os valores de category e status seguem o vocabulário já usado pelo frontend (data/mockPlaces.ts);
-- moradia e apoio são categorias novas, pedidas pelos prédios listados em docs/coordenadas_ufrpe.docx.

create table public.places (
    id                  bigint generated by default as identity primary key,
    -- identificador estável usado nas URLs (/locais/<slug>) e no localStorage do navegador.
    slug                text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    name                text not null check (btrim(name) <> ''),
    short_name          text,
    category            text not null check (category in (
                            'departamento', 'administrativo', 'biblioteca', 'alimentacao', 'sala',
                            'portaria', 'saude', 'auditorio', 'esporte', 'moradia', 'apoio')),
    -- RN-UC14.02: só 'publicado' aparece no mapa e na busca.
    status              text not null default 'rascunho' check (status in ('publicado', 'rascunho', 'inativo')),
    latitude            double precision check (latitude between -90 and 90),
    longitude           double precision check (longitude between -180 and 180),
    -- de onde veio a coordenada; ajuda a saber o que ainda precisa de conferência em campo.
    coordinates_source  text,
    address             text,
    hours               text,
    description         text,
    phone               text,
    email               text,
    -- latitude e longitude andam juntas.
    constraint places_coordinates_together check ((latitude is null) = (longitude is null)),
    -- RN-UC14.01: publicar exige georreferenciamento.
    constraint places_published_needs_coordinates check (status <> 'publicado' or latitude is not null)
);

-- set null: apagar um local não apaga o departamento, só desfaz o vínculo.
alter table public.departments
    add column place_id bigint references public.places (id) on delete set null;

create index departments_place_id_idx on public.departments (place_id);

-- RLS ligado sem policies e sem grants: o único caminho de acesso é o backend (nada exposto ao anon).
alter table public.places enable row level security;

revoke all on table public.places from anon, authenticated;
