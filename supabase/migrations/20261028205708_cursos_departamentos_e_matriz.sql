-- UC35, UC36, UC37: departamentos, cursos (com coordenação) e matriz curricular.
-- O departamento ainda não aponta para um local: o backend não tem tabela de locais. O vínculo entra
-- numa migration futura, quando essa tabela existir.
-- Valores de level, type e nature ficam em maiúsculas para casar com os enums Java (EnumType.STRING).

create table public.departments (
    id              bigint generated by default as identity primary key,
    code            text,
    name            text not null check (btrim(name) <> ''),
    short_name      text,
    academic_center text,
    description     text,
    address         text,
    hours           text,
    phone           text,
    email           text,
    founded_year    smallint check (founded_year between 1800 and 2200),
    active          boolean not null default true
);

create table public.courses (
    id                  bigint generated by default as identity primary key,
    -- restrict: apagar um departamento nunca apaga cursos em cascata (o hard delete é só do UC36).
    department_id       bigint not null references public.departments (id) on delete restrict,
    code                text,
    -- RN-UC35-01: o nome do curso não pode ficar em branco.
    name                text not null check (btrim(name) <> ''),
    level               text not null check (level in ('GRADUACAO', 'POS')),
    -- RN-UC37-01: a ordem de exibição é Bacharelado, Licenciatura e Stricto Sensu.
    type                text not null check (type in ('BACHARELADO', 'LICENCIATURA', 'STRICTO_SENSU')),
    modality            text,
    shift               text,
    duration_semesters  smallint check (duration_semesters > 0),
    mec_grade           smallint check (mec_grade between 1 and 5),
    capes_grade         smallint check (capes_grade between 1 and 7),
    description         text,
    -- RN-UC37-02: o total de programas conta só cursos ativos.
    active              boolean not null default true,
    coordinator_name    text,
    vice_coordinator_name text,
    office_location     text,
    office_hours        text,
    attendance_mode     text,
    phone               text,
    extension           text,
    email               text,
    secondary_email     text
);

create index courses_department_id_idx on public.courses (department_id);

create table public.curriculum_subjects (
    id              bigint generated by default as identity primary key,
    -- cascade: o UC36 remove o curso junto com a matriz curricular.
    course_id       bigint not null references public.courses (id) on delete cascade,
    -- null = bloco "Optativas / Eletivas".
    period          smallint check (period between 1 and 12),
    code            text not null check (btrim(code) <> ''),
    name            text not null check (btrim(name) <> ''),
    syllabus        text,
    workload_hours  smallint not null check (workload_hours > 0),
    credits         smallint check (credits >= 0),
    nature          text not null check (nature in ('OBRIGATORIA', 'OPTATIVA')),
    -- códigos de outras disciplinas separados por vírgula; vazio = "Nenhum".
    prerequisites   text,
    unique (course_id, code)
);

-- RLS ligado sem policies e sem grants: o único caminho de acesso é o backend, que conecta como dono
-- das tabelas e não é afetado pelo RLS (nada exposto ao anon nem ao authenticated).
alter table public.departments         enable row level security;
alter table public.courses             enable row level security;
alter table public.curriculum_subjects enable row level security;

revoke all on table public.departments         from anon, authenticated;
revoke all on table public.courses             from anon, authenticated;
revoke all on table public.curriculum_subjects from anon, authenticated;
