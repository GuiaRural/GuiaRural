-- Conteúdo do guia de acolhimento que estava fixo no frontend (data/mockGuides.ts e data/mockGuide.ts):
-- contatos de apoio e números de emergência, cartilhas para baixar e o aviso de apoio do Guia de Recife.
-- Tradução em colunas _pt / _en / _es (RF04): o português é obrigatório e o aplicativo cai para ele
-- quando falta EN ou ES. Nomes de unidade, e-mails, telefones e URLs não se traduzem.
-- Links só em https:// (RNF02), mailto: ou tel:; arquivos do próprio site começam com uma única barra.

-- Contatos ------------------------------------------------------------------------------------------------
create table public.guide_contacts (
    id        bigint generated by default as identity primary key,
    -- apoio: setores da UFRPE que atendem o estudante; emergencia: números públicos (polícia, SAMU, bombeiros).
    kind      text not null check (kind in ('apoio', 'emergencia')),
    label_pt  text not null check (btrim(label_pt) <> ''),
    label_en  text,
    label_es  text,
    -- o que aparece na tela: e-mail, telefone ou número de emergência.
    value     text not null check (btrim(value) <> ''),
    href      text not null check (href ~ '^(mailto:|tel:|https://)'),
    position  integer not null default 0,
    -- a tela usa o link como chave da lista: não pode repetir dentro do mesmo tipo.
    constraint guide_contacts_kind_href_key unique (kind, href)
);

create index guide_contacts_kind_position_idx on public.guide_contacts (kind, position);

-- Cartilhas e guias para baixar ---------------------------------------------------------------------------
create table public.guide_downloads (
    id              bigint generated by default as identity primary key,
    label_pt        text not null check (btrim(label_pt) <> ''),
    label_en        text,
    label_es        text,
    -- etiqueta do idioma do arquivo (ex.: "PT", "PT · EN"); é um código, não passa por tradução.
    language_label  text not null check (btrim(language_label) <> ''),
    -- arquivo em /public (começa com uma barra) ou página externa em https.
    href            text not null check (href ~ '^(/[^/]|https://)'),
    position        integer not null default 0,
    constraint guide_downloads_href_key unique (href)
);

create index guide_downloads_position_idx on public.guide_downloads (position);

-- Aviso de apoio (frase + botão) ---------------------------------------------------------------------------
-- A frase é montada como  before + highlight (em negrito) + after; os espaços nas bordas de before/after
-- fazem parte do texto, por isso não há trim nas colunas.
create table public.guide_support_banners (
    id            bigint generated by default as identity primary key,
    -- onde o aviso aparece (ex.: 'recife' = Guia de Recife).
    slug          text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    before_pt     text not null,
    before_en     text,
    before_es     text,
    -- nome da unidade, em negrito: sigla institucional, não se traduz.
    highlight     text not null check (btrim(highlight) <> ''),
    after_pt      text not null,
    after_en      text,
    after_es      text,
    cta_label_pt  text not null check (btrim(cta_label_pt) <> ''),
    cta_label_en  text,
    cta_label_es  text,
    cta_href      text not null check (cta_href ~ '^(/[^/]|https://)'),
    -- idiomas cujo texto é tradução automática ainda sem revisão humana (ver o ALTER abaixo).
    machine_translated_langs text[] not null default '{}'
        check (machine_translated_langs <@ array['en', 'es']::text[])
);

-- Tradução sugerida -----------------------------------------------------------------------------------------
-- machine_translated_langs lista os idiomas (en, es) cujo texto foi traduzido automaticamente e ainda espera
-- revisão humana. Quem revisar remove o idioma da lista. Vazio = tudo escrito ou revisado por pessoa.
-- Hoje cobre só o Guia de Recife (guide_spots, guide_tips e o aviso de apoio); os tópicos de acolhimento
-- vieram prontos do mock.
alter table public.guide_spots
    add column machine_translated_langs text[] not null default '{}'
        check (machine_translated_langs <@ array['en', 'es']::text[]);

alter table public.guide_tips
    add column machine_translated_langs text[] not null default '{}'
        check (machine_translated_langs <@ array['en', 'es']::text[]);

-- RLS ligado sem policies e sem grants: o único caminho de acesso é o backend (nada exposto ao anon).
alter table public.guide_contacts        enable row level security;
alter table public.guide_downloads       enable row level security;
alter table public.guide_support_banners enable row level security;

revoke all on table public.guide_contacts        from anon, authenticated;
revoke all on table public.guide_downloads       from anon, authenticated;
revoke all on table public.guide_support_banners from anon, authenticated;
