-- CT-040.02 a 040.04: categorias fixas do filtro do Guia de Recife.
-- Antes o filtro usava a etiqueta (tag) de cada lugar, que tem 8 rótulos para 10 lugares e nunca fica vazia.
-- A categoria é uma lista fixa, separada da etiqueta (que continua só como selo colorido do cartão).
-- Uma categoria pode ficar sem lugares: é o que a tela mostra como "Nenhum local encontrado nesta categoria".
-- Os nomes e o mapeamento lugar -> categoria foram aprovados pelo time em 21/11/2026. "Gastronomia" nasce sem
-- lugares, só como marcador a confirmar. EN/ES são tradução automática e esperam revisão humana.
create table public.guide_spot_categories (
    id                      bigint generated by default as identity primary key,
    slug                    text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    label_pt                text not null check (btrim(label_pt) <> ''),
    label_en                text,
    label_es                text,
    position                integer not null default 0,
    machine_translated_langs text[] not null default '{}'
        check (machine_translated_langs <@ array['en', 'es']::text[])
);

-- on delete restrict: apagar uma categoria em uso não solta os lugares sem aviso. Nulo = lugar sem categoria ("Outros").
alter table public.guide_spots
    add column category_id bigint references public.guide_spot_categories (id) on delete restrict;

create index guide_spots_category_id_idx on public.guide_spots (category_id);

-- Segurança (CLAUDE.md §9): RLS sem policies e nada para anon/authenticated; só o backend (dono) acessa.
alter table public.guide_spot_categories enable row level security;
revoke all on table public.guide_spot_categories from anon, authenticated;

