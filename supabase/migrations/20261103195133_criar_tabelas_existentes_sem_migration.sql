-- services, avisos, messages e contacts foram criadas pelo Hibernate (ddl-auto=update) e nenhuma migration
-- as criava: num ambiente novo, a migration de RLS (20261029135223) falha porque elas não existem.
-- Esta migration fecha a lacuna com as mesmas colunas das entidades JPA. É idempotente: no banco onde o
-- Hibernate já criou as tabelas, o "if not exists" não muda nada (só entram o índice e a FK de contacts).
--
-- ATENÇÃO à ordem: esta migration tem versão posterior à 20261029135223. Em ambiente novo, aplique
-- as migrations só depois de o backend (ddl-auto=update) ter criado essas quatro tabelas, ou ajuste a ordem
-- no bootstrap. Não reescrevemos a migration antiga porque ela já foi aplicada.

create table if not exists public.services (
    id                  bigint generated by default as identity primary key,
    name                varchar(255),
    description         varchar(255),
    location_reference  varchar(255),
    active              boolean
);

create table if not exists public.avisos (
    id          bigint generated by default as identity primary key,
    nome        varchar(255) not null,
    descricao   text not null,
    data        timestamp(6) not null
);

create table if not exists public.messages (
    id        bigint generated by default as identity primary key,
    nome      varchar(255) not null,
    email     varchar(255) not null,
    telefone  varchar(255),
    mensagem  varchar(500) not null
);

create table if not exists public.contacts (
    id        bigint generated by default as identity primary key,
    name      varchar(150) not null,
    email     varchar(150),
    phone     varchar(20),
    place_id  bigint not null
);

-- A entidade ContactEntity já pedia esta FK no banco. cascade: o contato pertence ao local.
do $$
begin
    if not exists (
        select 1 from pg_constraint
        where conname = 'contacts_place_id_fkey' and conrelid = 'public.contacts'::regclass
    ) then
        alter table public.contacts
            add constraint contacts_place_id_fkey
            foreign key (place_id) references public.places (id) on delete cascade;
    end if;
end $$;

create index if not exists contacts_place_id_idx on public.contacts (place_id);

-- Mesma regra das demais tabelas: RLS sem policies e nada para anon/authenticated (idempotente).
alter table public.services enable row level security;
alter table public.avisos   enable row level security;
alter table public.messages enable row level security;
alter table public.contacts enable row level security;

revoke all on table public.services from anon, authenticated;
revoke all on table public.avisos   from anon, authenticated;
revoke all on table public.messages from anon, authenticated;
revoke all on table public.contacts from anon, authenticated;
