-- UC12/UC13 (administradores) e UC23 / RNF06 (auditoria do painel).
-- O login continua mock no frontend por decisão do time: esta tabela NÃO guarda senha nem hash. Quando a
-- autenticação for decidida, as credenciais entram em migration própria (nunca senha em texto).

create table public.admins (
    id          bigint generated by default as identity primary key,
    name        text not null check (btrim(name) <> ''),
    -- RN-UC12-01: só e-mail institucional, sempre em minúsculas para a unicidade valer.
    email       text not null check (email = lower(email) and email ~ '^[^@[:space:]]+@ufrpe\.br$'),
    -- A lista de setores vive no aplicativo (SECTORS); não travamos aqui para não exigir migration a cada setor.
    sector      text not null check (btrim(sector) <> ''),
    permission  text not null check (permission in ('geral', 'editor', 'leitura')),
    -- RN-UC12-02: só 'ativo' entra. Quem sai vira 'revogado' (a linha nunca é apagada: a auditoria aponta para ela).
    status      text not null default 'aguardando' check (status in ('ativo', 'aguardando', 'revogado')),
    created_at  timestamptz not null default now()
);

create unique index admins_email_key on public.admins (email);

create table public.audit_logs (
    id            bigint generated always as identity primary key,
    at            timestamptz not null default now(),
    -- no action (e não set null): o log é imutável, então apagar o admin não pode reescrever a linha.
    admin_id      bigint references public.admins (id),
    -- nome no momento da ação: continua legível mesmo se o cadastro mudar depois.
    author        text not null check (btrim(author) <> ''),
    entity        text not null check (entity in ('local', 'servico', 'cardapio', 'aviso', 'acolhimento', 'administrador')),
    -- texto porque os ids do painel não são todos numéricos (ex.: slug do local, id do tópico de acolhimento).
    entity_id     text not null,
    entity_name   text not null,
    action        text not null check (action in ('criado', 'editado', 'deletado', 'restaurado')),
    -- Snapshots (Memento) antes e depois: base do "desfazer" do UC23. Nulos quando o registro não existia / deixou de existir.
    before_state  jsonb,
    after_state   jsonb,
    constraint audit_logs_has_snapshot check (before_state is not null or after_state is not null)
);

create index audit_logs_at_idx     on public.audit_logs (at desc);
create index audit_logs_entity_idx on public.audit_logs (entity, entity_id);

-- RNF06: o log só recebe inserções. "Desfazer" grava um novo log 'restaurado'; nunca edita o antigo.
create function public.audit_logs_block_changes()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    raise exception 'audit_logs é somente de inserção (% bloqueado)', tg_op;
end;
$$;

revoke execute on function public.audit_logs_block_changes() from public, anon, authenticated;

create trigger audit_logs_no_update_delete
    before update or delete on public.audit_logs
    for each row execute function public.audit_logs_block_changes();

create trigger audit_logs_no_truncate
    before truncate on public.audit_logs
    for each statement execute function public.audit_logs_block_changes();

-- RLS ligado sem policies e sem grants: o único caminho de acesso é o backend (nada exposto ao anon).
alter table public.admins     enable row level security;
alter table public.audit_logs enable row level security;

revoke all on table public.admins     from anon, authenticated;
revoke all on table public.audit_logs from anon, authenticated;
