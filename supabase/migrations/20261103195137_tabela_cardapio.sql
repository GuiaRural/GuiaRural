-- UC25: cardápio do RU. Os pratos são nomes próprios de comida, em português; sem colunas de tradução por ora.

create table public.menus (
    id          bigint generated by default as identity primary key,
    menu_date   date not null,
    shift       text not null check (shift in ('almoco', 'jantar')),
    main        text not null check (btrim(main) <> ''),
    vegetarian  text,
    sides       text,
    salad       text,
    dessert     text,
    drink       text,
    -- um cardápio por data e turno.
    constraint menus_date_shift_key unique (menu_date, shift)
);

-- RLS ligado sem policies e sem grants: o único caminho de acesso é o backend (nada exposto ao anon).
alter table public.menus enable row level security;

revoke all on table public.menus from anon, authenticated;
