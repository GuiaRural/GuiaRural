-- RF05 (guia de acolhimento cultural) e UC40 (Guia de Recife & RMR).
-- Tradução em colunas _pt / _en / _es (RF04). O português é obrigatório; EN e ES são opcionais e o
-- aplicativo cai para o português quando faltam (mesma regra do tipo Translated do frontend).
-- Os blocos de conteúdo e os links ficam em jsonb, uma coluna por idioma, sempre um array JSON.

create table public.guide_topics (
    id          bigint generated by default as identity primary key,
    -- identificador estável usado nas URLs e no progresso salvo no navegador (ex.: checklists).
    slug        text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    section     text not null check (section in ('cultura', 'documentos', 'calouro', 'recife')),
    stage       text check (stage in ('antes', 'chegada', 'primeiras-semanas', 'mobilidade')),
    title_pt    text not null check (btrim(title_pt) <> ''),
    title_en    text,
    title_es    text,
    summary_pt  text not null,
    summary_en  text,
    summary_es  text,
    blocks_pt   jsonb not null default '[]'::jsonb check (jsonb_typeof(blocks_pt) = 'array'),
    blocks_en   jsonb check (jsonb_typeof(blocks_en) = 'array'),
    blocks_es   jsonb check (jsonb_typeof(blocks_es) = 'array'),
    -- itens {"label": ..., "url": ...} com o rótulo no idioma da coluna.
    links_pt    jsonb not null default '[]'::jsonb check (jsonb_typeof(links_pt) = 'array'),
    links_en    jsonb check (jsonb_typeof(links_en) = 'array'),
    links_es    jsonb check (jsonb_typeof(links_es) = 'array'),
    source_pt   text,
    source_en   text,
    source_es   text,
    -- set null: apagar o local não apaga o tópico, só desfaz o vínculo.
    place_id    bigint references public.places (id) on delete set null,
    position    integer not null default 0
);

create index guide_topics_section_idx  on public.guide_topics (section, position);
create index guide_topics_place_id_idx on public.guide_topics (place_id);

create table public.guide_spots (
    id                  bigint generated by default as identity primary key,
    slug                text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    title_pt            text not null check (btrim(title_pt) <> ''),
    title_en            text,
    title_es            text,
    -- endereço é nome de rua: não se traduz.
    address             text,
    description_pt      text not null,
    description_en      text,
    description_es      text,
    tag_label_pt        text,
    tag_label_en        text,
    tag_label_es        text,
    tag_tone            text check (tag_tone in ('red', 'navy', 'olive')),
    badge_label_pt      text,
    badge_label_en      text,
    badge_label_es      text,
    badge_tone          text check (badge_tone in ('free', 'highlight')),
    distance_label_pt   text,
    distance_label_en   text,
    distance_label_es   text,
    distance_icon       text,
    image_url           text,
    image_alt_pt        text,
    image_alt_en        text,
    image_alt_es        text,
    details_layout      text not null default 'stack' check (details_layout in ('stack', 'columns')),
    -- itens {"label": ..., "text": ..., "icon": ..., "iconTone": ..., "emphasis": ...}.
    details_pt          jsonb not null default '[]'::jsonb check (jsonb_typeof(details_pt) = 'array'),
    details_en          jsonb check (jsonb_typeof(details_en) = 'array'),
    details_es          jsonb check (jsonb_typeof(details_es) = 'array'),
    position            integer not null default 0
);

create index guide_spots_position_idx on public.guide_spots (position);

create table public.guide_tips (
    id              bigint generated by default as identity primary key,
    slug            text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    icon            text,
    title_pt        text not null check (btrim(title_pt) <> ''),
    title_en        text,
    title_es        text,
    text_pt         text not null,
    text_en         text,
    text_es         text,
    link_label_pt   text,
    link_label_en   text,
    link_label_es   text,
    link_href       text,
    position        integer not null default 0
);

create index guide_tips_position_idx on public.guide_tips (position);

-- RLS ligado sem policies e sem grants: o único caminho de acesso é o backend (nada exposto ao anon).
alter table public.guide_topics enable row level security;
alter table public.guide_spots  enable row level security;
alter table public.guide_tips   enable row level security;

revoke all on table public.guide_topics from anon, authenticated;
revoke all on table public.guide_spots  from anon, authenticated;
revoke all on table public.guide_tips   from anon, authenticated;
