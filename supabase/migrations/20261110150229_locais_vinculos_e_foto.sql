-- Fase 1 do plano de integração (docs/plano-integracao-banco.md): o que o formulário de local precisa guardar.
--   serviços do local  -> place_service: liga o local a serviços do catálogo (D11). A tabela já existia no banco, mas
--                         sem migration e sem código; aqui ela passa a ser versionada e ganha as regras que faltavam.
--   cursos vinculados  -> place_courses (nova)
--   foto               -> place_photos (nova, D2): a imagem fica no PostgreSQL, já reduzida pelo backend, e só o
--                         backend a lê e grava (nada exposto ao anon).
-- O responsável do local continua em contacts (a FK com on delete cascade já existe na migration 20261103195133).
-- Mesma regra das demais tabelas: RLS ligado, sem policies, nada para anon/authenticated.

-- ---------------------------------------------------------------------------------------------------------------
-- place_service
-- ---------------------------------------------------------------------------------------------------------------
-- "if not exists": em um ambiente novo ela ainda não existe; no banco atual já existe (0 linhas) e nada muda aqui.
create table if not exists public.place_service (
    id          bigint generated by default as identity primary key,
    place_id    bigint not null,
    service_id  bigint
);

alter table public.place_service alter column service_id set not null;

-- cascade: apagar o local ou o serviço desfaz só o vínculo.
alter table public.place_service drop constraint if exists place_service_place_id_fkey;
alter table public.place_service
    add constraint place_service_place_id_fkey
    foreign key (place_id) references public.places (id) on delete cascade;

alter table public.place_service drop constraint if exists place_service_service_id_fkey;
alter table public.place_service
    add constraint place_service_service_id_fkey
    foreign key (service_id) references public.services (id) on delete cascade;

-- Um serviço não se repete dentro do mesmo local.
create unique index if not exists place_service_place_id_service_id_key
    on public.place_service (place_id, service_id);
create index if not exists place_service_service_id_idx on public.place_service (service_id);

alter table public.place_service enable row level security;
revoke all on table public.place_service from anon, authenticated;

-- ---------------------------------------------------------------------------------------------------------------
-- place_courses
-- ---------------------------------------------------------------------------------------------------------------
create table public.place_courses (
    place_id   bigint not null references public.places (id) on delete cascade,
    -- cascade: o UC36 exclui o curso de verdade, e o vínculo some junto.
    course_id  bigint not null references public.courses (id) on delete cascade,
    primary key (place_id, course_id)
);

create index place_courses_course_id_idx on public.place_courses (course_id);

alter table public.place_courses enable row level security;
revoke all on table public.place_courses from anon, authenticated;

-- ---------------------------------------------------------------------------------------------------------------
-- place_photos
-- ---------------------------------------------------------------------------------------------------------------
-- Uma foto por local. O backend aceita JPG/PNG de até 5 MB (RNF01), reduz e regrava em JPEG; o check abaixo é a
-- segunda barreira (mesmo limite, só JPEG). A lista do mapa nunca lê esta tabela: só o endpoint da foto.
create table public.place_photos (
    place_id      bigint primary key references public.places (id) on delete cascade,
    content_type  text not null check (content_type = 'image/jpeg'),
    bytes         bytea not null check (octet_length(bytes) between 1 and 5242880),
    updated_at    timestamptz not null default now()
);

alter table public.place_photos enable row level security;
revoke all on table public.place_photos from anon, authenticated;
