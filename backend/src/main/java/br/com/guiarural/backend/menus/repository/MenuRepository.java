package br.com.guiarural.backend.menus.repository;

import br.com.guiarural.backend.menus.model.MenuEntity;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.Modifying;
import org.springframework.data.jpa.repository.Query;
import org.springframework.data.repository.query.Param;

import java.time.LocalDate;
import java.util.List;

public interface MenuRepository extends JpaRepository<MenuEntity, Long> {
    List<MenuEntity> findAllByOrderByMenuDateAscShiftAsc();

    List<MenuEntity> findByMenuDateBetweenOrderByMenuDateAscShiftAsc(LocalDate from, LocalDate to);

    boolean existsByMenuDateAndShift(LocalDate menuDate, String shift);

    boolean existsByMenuDateAndShiftAndIdNot(LocalDate menuDate, String shift, Long id);

    // Desfazer uma exclusão (UC23) devolve o cardápio com o id original, para o histórico continuar apontando para ele.
    // O JPA não insere id escolhido numa coluna identity; a linha nasce com id novo e troca para o antigo (que ficou
    // livre na exclusão). A coluna é "generated by default", então aceita a troca.
    @Modifying(flushAutomatically = true, clearAutomatically = true)
    @Query(value = "update menus set id = :original where id = :current", nativeQuery = true)
    void restoreId(@Param("current") Long current, @Param("original") Long original);
}
