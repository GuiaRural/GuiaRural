package br.com.guiarural.backend.services.repository;

import br.com.guiarural.backend.services.model.ServiceEntity;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.Modifying;
import org.springframework.data.jpa.repository.Query;
import org.springframework.data.repository.query.Param;
import org.springframework.stereotype.Repository;

import java.util.List;
import java.util.Optional;

@Repository
public interface ServiceRepository extends JpaRepository<ServiceEntity, Long> {
    // Catálogo público (RF03): só serviços publicados.
    List<ServiceEntity> findByActiveTrueOrderByNameAsc();

    Optional<ServiceEntity> findByIdAndActiveTrue(Long id);

    // Visão do painel: todos, na ordem de cadastro.
    List<ServiceEntity> findAllByOrderByIdAsc();

    // Desfazer uma exclusão (UC23) devolve o serviço com o id original, para o histórico e os vínculos com locais
    // continuarem valendo. O JPA não insere id escolhido numa coluna identity; a linha nasce com id novo e troca para o
    // antigo (que ficou livre na exclusão). A coluna é "generated by default", então aceita a troca.
    @Modifying(flushAutomatically = true, clearAutomatically = true)
    @Query(value = "update services set id = :original where id = :current", nativeQuery = true)
    void restoreId(@Param("current") Long current, @Param("original") Long original);
}
